package dev.boqing.strongholdplacefix.mixin;

import dev.boqing.strongholdplacefix.ForcedPlacement;
import dev.boqing.strongholdplacefix.StrongholdPlaceFix;
import net.minecraft.core.BlockPos;
import net.minecraft.util.Mth;
import net.minecraft.util.RandomSource;
import net.minecraft.world.level.levelgen.structure.BoundingBox;
import net.minecraft.world.level.levelgen.structure.pieces.StructurePiecesBuilder;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

/**
 * Replaces the random vertical relocation of a stronghold with a deterministic one
 * when the structure is being generated by {@code /place structure}.
 *
 * <p>Vanilla {@code moveBelowSeaLevel(seaLevel, minY, random, spread)} moves the
 * structure so its top Y is a random value between {@code (height + minY + 1)} and
 * {@code seaLevel - spread}.  For strongholds this puts the structure tens of blocks
 * underground no matter which Y the player requested.  Here we instead move it so the
 * structure's top Y equals the requested Y (clamped to stay inside the world).</p>
 */
@Mixin(StructurePiecesBuilder.class)
public abstract class StructurePiecesBuilderMixin {
    @Inject(method = "m_226965_", at = @At("HEAD"), cancellable = true)
    private void strongholdplacefix$forceStrongholdY(
            int seaLevel,
            int minY,
            RandomSource random,
            int spread,
            CallbackInfoReturnable<Integer> cir) {
        BlockPos target = ForcedPlacement.get();
        if (target == null) {
            return;
        }

        StructurePiecesBuilder self = (StructurePiecesBuilder) (Object) this;
        BoundingBox box = self.getBoundingBox();
        int height = box.getYSpan();
        int oldMaxY = box.maxY();

        // Default 1.20.1 overworld is 384 blocks tall (minY .. minY + 383).
        int maxAllowedY = minY + 384 - 1;
        int minAllowedY = minY + height;
        if (minAllowedY > maxAllowedY) {
            minAllowedY = maxAllowedY;
        }

        int desiredMaxY = Mth.clamp(target.getY(), minAllowedY, maxAllowedY);
        int delta = desiredMaxY - oldMaxY;
        if (delta != 0) {
            self.offsetPiecesVertically(delta);
        }
        StrongholdPlaceFix.LOGGER.info(
                "[strongholdplacefix] stronghold top Y {} -> {} (delta {}) for request {}, bbox x {}..{} z {}..{} (chunks {}..{}, {}..{})",
                oldMaxY, desiredMaxY, delta, target,
                box.minX(), box.maxX(), box.minZ(), box.maxZ(),
                box.minX() >> 4, box.maxX() >> 4, box.minZ() >> 4, box.maxZ() >> 4);
        cir.setReturnValue(delta);
    }
}
